"""Install this package's usage guide as a coding-agent skill.

The skill is ``SKILL.md`` built from the installed ``ssatk/skills.md``, so it
always describes the installed version. It goes to the personal skills folder
``~/.claude/skills/ssatk/`` (under ``$CLAUDE_CONFIG_DIR`` when that is set);
``--dir`` installs into another skills folder, such as a project's, and
``--package`` writes a ``.skill`` archive for assistants that upload skills.

Run ``ssatk-skill`` again after upgrading SSATK to refresh the copy.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import zipfile
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

SKILL_NAME = "ssatk"
DESCRIPTION = (
    "Use when writing or reviewing Python that uses SSATK (ssatk): orbits, "
    "propagation, coordinate frames, maneuvers and transfers, conjunctions, ground tracks, "
    "eclipses, or space situational awareness. Lists the modules, conventions and functions "
    "that already exist so code reuses them instead of reimplementing them."
)
_REPOSITORY = "https://github.com/LLNL/ssatk/blob/main/"


def _installed_version() -> str:
    try:
        return version("ssatk")
    except PackageNotFoundError:
        return "unknown"


def skill_text() -> str:
    """``SKILL.md`` text: frontmatter plus the packaged usage guide."""
    guide = (Path(__file__).with_name("skills.md")).read_text(encoding="utf-8")
    # Repository-relative links do not resolve from an installed skill.
    guide = re.sub(r"\]\((?:\.\./)?(?!https?://|#)([^)]+)\)", lambda m: f"]({_REPOSITORY}{m.group(1)})", guide)
    return (
        f"---\nname: {SKILL_NAME}\ndescription: {json.dumps(DESCRIPTION)}\n---\n\n"
        f"<!-- Generated by ssatk-skill from ssatk {_installed_version()}; "
        "run ssatk-skill again after upgrading. -->\n\n" + guide
    )


def default_directory() -> Path:
    config = os.environ.get("CLAUDE_CONFIG_DIR")
    return (Path(config).expanduser() if config else Path.home() / ".claude") / "skills"


def install(directory: str | Path | None = None) -> Path:
    """Write ``<directory>/ssatk/SKILL.md`` and return its path."""
    target = Path(directory).expanduser() if directory else default_directory()
    path = target / SKILL_NAME / "SKILL.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(skill_text(), encoding="utf-8")
    return path


def package(output: str | Path) -> Path:
    """Write a ``.skill`` archive (``ssatk/SKILL.md`` in a zip) and return its path."""
    path = Path(output).expanduser()
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(f"{SKILL_NAME}/SKILL.md", skill_text())
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="ssatk-skill", description=__doc__.split("\n\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--dir", help=f"skills folder to install into (default: {default_directory()})")
    group.add_argument("--print", action="store_true", help="print SKILL.md instead of installing it")
    group.add_argument("--package", metavar="FILE", help="write a .skill archive for assistants that upload skills")
    args = parser.parse_args(argv)
    if args.print:
        print(skill_text(), end="")
    elif args.package:
        print(package(args.package))
    else:
        print(install(args.dir))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
