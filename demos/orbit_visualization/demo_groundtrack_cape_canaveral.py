"""Cape Canaveral visibility for a synthetic ISS-class circular orbit.

The orbit is generated by SSAPy's ``Orbit.fromKeplerianElements`` and
``ssapy.rv``.  Its right ascension of ascending node and argument of latitude
are chosen for a pass near zenith at Cape Canaveral at the midpoint of the
one-period arc.
"""

from __future__ import annotations

import os
import sys

import matplotlib.pyplot as plt
import numpy as np
from astropy.time import Time
from astropy.coordinates import EarthLocation
import astropy.units as u

from ssapy import Orbit, rv

from ssatk.constants import EARTH_MU, WGS84_A_KM
from ssatk.coordinates.frames import eci_to_ecf_matrix
from ssatk.plots.groundtrack_enhanced import plot_enhanced_groundtrack
from ssatk.plots.plotutils import figsave


GALLERY_CATEGORY = "orbit_visualization"
SITE_LAT = 28.39
SITE_LON = -80.60
SITE_NAME = "Cape Canaveral"
MIN_ELEV_DEG = 10.0
ALTITUDE_KM = 408.0
INCLINATION_DEG = 51.6
EPOCH = Time("2025-07-02T00:00:00", scale="utc")
UNDER_PYTEST = "pytest" in sys.modules or os.environ.get("PYTEST_CURRENT_TEST") is not None


def _oriented_elements(epoch: Time) -> tuple[float, float]:
    """Return (RAAN, argument of latitude) for a site pass."""
    site = EarthLocation.from_geodetic(SITE_LON * u.deg, SITE_LAT * u.deg)
    site_itrf_m = site.get_itrs(obstime=epoch).cartesian.xyz.to_value(u.m)
    # Use the same SSAPy frame matrix as the enhanced plotter so the designed
    # midpoint pass is consistent with the rendered ground track.
    ecf_from_eci = np.asarray(eci_to_ecf_matrix(epoch.gps)).reshape(3, 3)
    site_gcrf_m = ecf_from_eci.T @ site_itrf_m
    target = site_gcrf_m / np.linalg.norm(site_gcrf_m)
    inc = np.radians(INCLINATION_DEG)

    # r = R3(RAAN) R1(i) [cos(u), sin(u), 0].  Select the ascending solution
    # that contains the target direction, then solve RAAN from x/y.
    sin_u = np.clip(target[2] / np.sin(inc), -1.0, 1.0)
    argument_latitude = np.arcsin(sin_u)
    a_xy = np.cos(argument_latitude)
    b_xy = np.sin(argument_latitude) * np.cos(inc)
    raan = np.arctan2(target[1], target[0]) - np.arctan2(b_xy, a_xy)
    return raan, argument_latitude


def make_cape_canaveral_orbit(*, fast: bool = False):
    """Generate one period of <=10 s SSAPy samples and Astropy times."""
    radius_m = (WGS84_A_KM + ALTITUDE_KM) * 1000.0
    period_s = 2.0 * np.pi * np.sqrt(radius_m**3 / EARTH_MU)
    midpoint = EPOCH + (period_s / 2.0) * u.s
    raan, argument_latitude = _oriented_elements(midpoint)
    orbit = Orbit.fromKeplerianElements(
        a=radius_m,
        e=0.0,
        i=np.radians(INCLINATION_DEG),
        pa=0.0,
        raan=raan,
        trueAnomaly=argument_latitude,
        t=midpoint,
        mu=EARTH_MU,
    )
    # Keep both fast and full gallery modes at a 10 s maximum sample spacing.
    step_s = 10.0
    count = int(np.ceil(period_s / step_s)) + 1
    if count % 2 == 0:
        count += 1  # include the designed midpoint pass as an actual sample
    offsets_s = np.linspace(0.0, period_s, count)
    gps_times = EPOCH.gps + offsets_s
    r_m, v_m_s = rv(orbit, gps_times)
    times = EPOCH + offsets_s * u.s
    return orbit, r_m / 1000.0, v_m_s / 1000.0, times, period_s


def main(make_figures=None, fast=None):
    if make_figures is None:
        make_figures = not UNDER_PYTEST
    if fast is None:
        fast = UNDER_PYTEST

    orbit, r_km, v_km_s, times, period_s = make_cape_canaveral_orbit(fast=fast)
    # gallery-call: demo_groundtrack_cape_canaveral.jpg
    fig, _ax, stats = plot_enhanced_groundtrack(
        r_eci_km=r_km,
        t=times,
        site_lat=SITE_LAT,
        site_lon=SITE_LON,
        site_name=SITE_NAME,
        sat_name=f"{ALTITUDE_KM:.0f} km, {INCLINATION_DEG:.1f} deg circular LEO",
        min_elev_deg=MIN_ELEV_DEG,
    )
    # gallery-end

    if make_figures:
        figsave(fig, "demo_groundtrack_cape_canaveral.jpg")
    else:
        plt.close(fig)

    return {
        "orbit": orbit,
        "r_km": r_km,
        "v_km_s": v_km_s,
        "times": times,
        "period_s": period_s,
        "sample_step_s": float(np.max(np.diff(times.gps))),
        "stats": stats,
    }


if __name__ == "__main__":
    main(make_figures=True, fast=False)
